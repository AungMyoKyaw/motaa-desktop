pub(crate) fn android_apparent(jde: f64, mode: usize) -> Option<f64> {
    if mode >= 9 || !jde.is_finite() {
        return None;
    }
    let day = jde.clamp(ANDROID_MEAN[0][0], ANDROID_MEAN[31][0]);
    let first = ANDROID_MEAN
        .partition_point(|row| row[0] < day)
        .saturating_sub(2)
        .min(28);
    let anchors = &ANDROID_MEAN[first..first + 4];
    let mean: f64 = anchors
        .iter()
        .enumerate()
        .map(|(index, row)| {
            let basis: f64 = anchors
                .iter()
                .enumerate()
                .filter(|(i, _)| *i != index)
                .map(|(_, other)| (day - other[0]) / (row[0] - other[0]))
                .product();
            row[mode + 1] * basis
        })
        .sum();
    Some(mean + astro::nutation::nutation(jde).0.to_degrees())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn compares_all_nine_modes_at_six_off_grid_dates() {
        let cases: Vec<(f64, [f64; 9])> =
            serde_json::from_str(include_str!("../data/reference-ayanamsa-oracle.json")).unwrap();
        assert_eq!(cases.len(), 6);
        for (jd, expected) in cases {
            for (mode, expected) in expected.into_iter().enumerate() {
                let observed = mean(jd, mode).unwrap();
                assert!(
                    (observed - expected).abs() < 0.0001,
                    "{jd} mode {mode}: {observed} vs {expected}"
                );
            }
        }
        assert!(mean(2451545., 9).is_none());
        assert!(mean(2_000_000., 0).is_none());
    }
}

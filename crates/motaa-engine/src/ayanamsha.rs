pub fn mean(jdut: f64, mode: usize) -> Option<f64> {
    if mode >= ANCHORS[0].len() || !(JULIAN_DAYS[0]..=JULIAN_DAYS[3]).contains(&jdut) {
        return None;
    }
    Some(
        JULIAN_DAYS
            .iter()
            .enumerate()
            .map(|(anchor, &day)| {
                let basis: f64 = JULIAN_DAYS
                    .iter()
                    .enumerate()
                    .filter(|(index, _)| *index != anchor)
                    .map(|(_, other)| (jdut - other) / (day - other))
                    .product();
                ANCHORS[anchor][mode] * basis
            })
            .sum(),
    )
}

